/**
 * The About section's requests. The page never names a URL or a path: windows refuse
 * window.open and navigation (security.ts), this handler opens only the company website, and
 * the notices handler reads only the one notices file the app ships, so a compromised page can
 * use them to launch or read nothing else.
 */
import { app, ipcMain, shell } from 'electron'
import { promises as fs } from 'node:fs'
import path from 'node:path'
import type { AppInfo } from '../shared/api/brand'
import { APP_NAME, COMPANY_URL } from '../shared/brand'
import { isAppUrl } from './security'

/** The third-party notices file (generated by scripts/notices.mjs, shipped through extraResources). */
export const NOTICES_FILE = 'THIRD_PARTY_NOTICES.txt'
/** Largest notices file read, bytes. */
const NOTICES_MAX = 2 << 20

/** Where the notices are: next to app.asar when packaged, in the repository's resources folder in development. */
export function noticesPath(): string {
  return app.isPackaged ? path.join(process.resourcesPath, NOTICES_FILE) : path.join(app.getAppPath(), 'resources', NOTICES_FILE)
}

/** The notices as text; rejects with a message to show when the file is missing or too large. */
export async function readNotices(file = noticesPath()): Promise<string> {
  const stat = await fs.stat(file).catch(() => null)
  if (!stat?.isFile()) throw new Error('The third-party notices are missing from this copy of Flown.')
  if (stat.size > NOTICES_MAX) throw new Error('The third-party notices file is too large to show.')
  return fs.readFile(file, 'utf8')
}

export function registerBrandIpc(): void {
  ipcMain.handle('brand:app-info', (): AppInfo => ({ name: APP_NAME, version: app.getVersion() }))
  ipcMain.handle('brand:open-website', () => shell.openExternal(COMPANY_URL))
  ipcMain.handle('brand:notices', (e) => {
    if (!isAppUrl(e.senderFrame?.url ?? '')) throw new Error('Not allowed')
    return readNotices()
  })
}
