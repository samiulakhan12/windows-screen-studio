/** Normalised (0..1) cursor position relative to the captured display, at time `t` (seconds). */
export interface CursorSample {
  t: number
  x: number
  y: number
}

export interface ClickEvent {
  t: number
  x: number
  y: number
  button: 'left' | 'right' | 'middle'
}

/** A shortcut-style keystroke (e.g. "Ctrl + C"); plain typing is never recorded. */
export interface KeyEvent {
  t: number
  label: string
}

export type CursorShape = 'arrow' | 'text' | 'pointer' | 'crosshair' | 'move' | 'resize-ew' | 'resize-ns' | 'wait'

/** Cursor shape changes (only available from the native Windows capture path). */
export interface CursorShapeEvent {
  t: number
  shape: CursorShape
}

export interface CursorTrack {
  samples: CursorSample[]
  clicks: ClickEvent[]
  keys?: KeyEvent[]
  shapes?: CursorShapeEvent[]
  /** "Zoom here" hotkey presses while recording (source seconds). */
  marks?: { t: number }[]
  /** Typing bursts (source seconds; which keys were typed is never recorded). */
  typing?: { t: number; end: number }[]
  /** Display scale factor (1 = 100%, 1.5 = 150%) of the captured monitor, for cursor sizing. */
  scale?: number
  /** False when the capture target was a window (cursor coordinates unknown). */
  valid: boolean
}

export type ZoomFocus =
  | { mode: 'cursor' }
  | { mode: 'fixed'; x: number; y: number }
  /** Frame exactly this normalised source rectangle (scale and centre follow from it). */
  | { mode: 'region'; x: number; y: number; w: number; h: number }

/** How a zoom moves in and out. */
export type ZoomEasing = 'smooth' | 'snappy' | 'bouncy' | 'linear'

export interface ZoomSegment {
  id: string
  start: number
  end: number
  scale: number
  focus: ZoomFocus
  /** True when generated by auto zoom (regenerating replaces only these). */
  auto: boolean
  /**
   * The click an auto zoom was made for (source seconds, normalised position): with cursor
   * focus the camera aims at it while zooming in and hands back to the cursor shortly after
   * it, so the zoom frames the click even when the cursor arrived just before. Absent in
   * older projects and in zooms made by hand.
   */
  anchor?: { t: number; x: number; y: number }
  /** Ease for this zoom's transitions (default: project zoomSettings.easing). */
  easing?: ZoomEasing
  /** Seconds the zoom takes to move in and out (default: project zoomSettings.transition). */
  transition?: number
}

/** How auto zoom turns recorded input into zoom segments. */
export interface AutoZoomSettings {
  enabled: boolean
  /** Zoom level of generated zooms. */
  scale: number
  /** Clicks closer than this (seconds) share one zoom. */
  clusterGap: number
  /** Seconds the zoom starts before the first click. */
  leadIn: number
  /** Seconds the zoom holds after the last click. */
  hold: number
  /** Right clicks also create zooms. */
  rightClicks: boolean
  /** Typing bursts (CursorTrack.typing) create zooms at the place being typed into. */
  onTyping: boolean
  /** "Zoom here" marks pressed while recording (CursorTrack.marks) create zooms. */
  onMarks: boolean
}

export interface ZoomSettings {
  /** Level of new manual zooms (below 1 pulls back to show more background). */
  defaultScale: number
  easing: ZoomEasing
  /** Default transition seconds. */
  transition: number
  auto: AutoZoomSettings
}
export type Background =
  | { type: 'gradient'; preset: string }
  | { type: 'color'; color: string }
  /** `blur`: 0 (sharp) .. 1 (strongly blurred), so the recording stands out. */
  | { type: 'image'; path: string; blur?: number }
  /** A generated wallpaper from the built-in pack (shared/engine/wallpapers.ts). */
  | { type: 'wallpaper'; id: string; blur?: number }
  /** A gradient that slowly moves while the video plays; `speed` 0.25..2 (default 1). */
  | { type: 'animated'; preset: string; speed?: number }

export type DeviceFrameKind = 'none' | 'browser' | 'laptop' | 'monitor' | 'phone'

/** Device chrome drawn around the recording. */
export interface DeviceFrame {
  kind: DeviceFrameKind
  theme: 'light' | 'dark'
  /** Address bar text of the browser frame. */
  title?: string
}

export type ShadowStyle = 'soft' | 'hard' | 'glow'

export interface CardBorder {
  /** Width in 1080p-referenced pixels; 0 = none. */
  width: number
  color: string
  /** Frosted, semi-transparent border (glass) instead of a solid one. */
  glass: boolean
}

export interface WatermarkSettings {
  show: boolean
  kind: 'image' | 'text'
  /** Project-relative image file (watermark.<ext>), for kind 'image'. */
  path?: string
  text?: string
  position: Corner | 'center'
  /** Width (image) or text height as a fraction of the output's shorter side. */
  size: number
  opacity: number
  /** Distance from the frame's edges as a fraction of the shorter side. */
  margin: number
}

export type AspectRatio = 'auto' | '16:9' | '9:16' | '1:1' | '4:3'
export type Corner = 'top-left' | 'top-right' | 'bottom-left' | 'bottom-right'

export interface StyleSettings {
  background: Background
  /** Padding as a fraction of the output's shorter side. */
  padding: number
  cornerRadius: number
  shadow: number
  aspectRatio: AspectRatio
  /** Device frame around the recording; absent = none. */
  frame?: DeviceFrame
  border?: CardBorder
  /** Look of the shadow; absent = 'soft' (the original drop shadow). */
  shadowStyle?: ShadowStyle
  /** Colour of a 'hard' or 'glow' shadow. */
  shadowColor?: string
}

/** 'auto' follows the recorded cursor shapes; the others force one look. */
export type CursorStyle = 'auto' | 'mac' | 'windows' | 'white' | 'black' | 'custom'
export type ClickStyle = 'ripple' | 'ring' | 'pulse'

export interface CursorSettings {
  show: boolean
  size: number
  /** 0 = raw movement, 1 = very smooth. */
  smoothing: number
  clickEffect: boolean
  hideWhenIdle: boolean
  style?: CursorStyle
  /** Project-relative image file used when style is 'custom' (hot spot = top-left). */
  customImage?: string
  /** Halo drawn around the cursor. */
  highlight?: { enabled: boolean; color: string; size: number; opacity: number }
  clickStyle?: ClickStyle
  clickColor?: string
  /** Play a click sound at every click (preview and export). */
  clickSound?: boolean
  /** 0..1 */
  clickSoundVolume?: number
  /** Glide the cursor back to where it started during the last second (seamless loops). */
  loopHome?: boolean
  /** Lean the cursor slightly in the direction it moves. */
  tilt?: boolean
  /** Short fading trail behind a moving cursor. */
  trail?: boolean
}

export interface WebcamSettings {
  show: boolean
  corner: Corner
  /** Diameter as a fraction of output height. */
  size: number
  shape: 'circle' | 'rounded'
}

/**
 * A kept piece of the recording, in source seconds. The output video is the
 * clips played back to back, each at its own speed; gaps between clips are cuts.
 */
export interface Clip {
  id: string
  start: number
  end: number
  speed: number
}

export type AnnotationStyle = 'pill' | 'title'

/** Text overlay shown between `start` and `end` (source seconds). */
export interface Annotation {
  id: string
  start: number
  end: number
  text: string
  /** Centre of the text, normalised to the output frame (0..1). */
  x: number
  y: number
  /** Font size as a fraction of the output frame's shorter side. */
  size: number
  style: AnnotationStyle
}

export interface KeystrokeSettings {
  show: boolean
  position: 'bottom' | 'top'
  /** Label size as a fraction of the output frame's shorter side. */
  size: number
}

export interface EffectSettings {
  /** 0 = off, 1 = strong. Applied to camera (zoom/pan) motion. */
  motionBlur: number
  keystrokes: KeystrokeSettings
}

export interface AudioTrackSettings {
  /** Linear gain, 0..2. */
  volume: number
  muted: boolean
}

export interface MusicSettings {
  /** Project-relative file (music.<ext>). */
  path: string
  /** Linear gain, 0..2. */
  volume: number
  /** How much the music is lowered while the recording has sound, 0 (never) .. 1 (to silence). */
  ducking: number
  /** Repeat the music when it is shorter than the video. */
  loop: boolean
  /** Fade lengths in seconds. */
  fadeIn: number
  fadeOut: number
}

export interface AudioSettings {
  /** Linear gain of the whole recording sound, 0..2. */
  volume: number
  muted: boolean
  /** Per-source settings when the recording kept the microphone and system sound apart (Project.audioStems). */
  mic?: AudioTrackSettings
  system?: AudioTrackSettings
  /** Background noise reduction, 0 (off) .. 1 (strong). */
  noiseReduction?: number
  /** Even out the loudness (about -16 LUFS). */
  normalize?: boolean
  /** Fade of the whole soundtrack at the start and end of the video, seconds. */
  fadeIn?: number
  fadeOut?: number
  music?: MusicSettings | null
}

export type ShapeKind = 'arrow' | 'line' | 'rect' | 'ellipse' | 'highlight' | 'blur' | 'pixelate'

/**
 * A shape drawn over the recording between `start` and `end` (source seconds). Positions are
 * normalised to the recorded video, so a shape stays on its content while the camera zooms.
 * Arrows and lines go from (x, y) to (x + w, y + h) (w and h may be negative); the other
 * kinds fill the box.
 */
export interface Shape {
  id: string
  start: number
  end: number
  kind: ShapeKind
  x: number
  y: number
  w: number
  h: number
  color: string
  /** Stroke width in 1080p-referenced pixels. */
  strokeWidth: number
  /** Filled instead of outlined (rect, ellipse). */
  fill: boolean
  opacity: number
  /** Blur radius or pixel size of 'blur' and 'pixelate', 0..1. */
  strength: number
}

/** Darkens everything but one area: around the cursor or a fixed region. */
export interface Spotlight {
  id: string
  start: number
  end: number
  mode: 'cursor' | 'region'
  /** The lit area, normalised to the recorded video; in 'cursor' mode only w and h are used. */
  x: number
  y: number
  w: number
  h: number
  shape: 'ellipse' | 'rect'
  /** How dark the rest gets, 0..1. */
  dim: number
  /** Edge softness, 0..1. */
  feather: number
}

/** Normalised rectangle (0..1) relative to the captured display. */
export interface NormRect {
  x: number
  y: number
  w: number
  h: number
}

export interface CaptureInfo {
  /** 'native' = Windows Graphics Capture helper; 'chromium' = Electron getDisplayMedia. */
  method: 'native' | 'chromium'
  /** True when the OS cursor is baked into the video pixels. */
  cursorInVideo: boolean
  /** Region of the display that was recorded (already cropped in the proxy), or null for the full source. */
  region: NormRect | null
  /** What was recorded (absent in older projects: 'screen', or 'area' when region is set). */
  target?: 'screen' | 'area' | 'window'
  /** Frame rate of the screen recording and its proxy (absent in older projects: 60). */
  fps?: number
}

export interface Project {
  version: 2
  id: string
  name: string
  createdAt: string
  /** Recording duration in seconds. */
  duration: number
  width: number
  height: number
  hasWebcam: boolean
  hasAudio: boolean
  /** Webcam start offset relative to screen start (seconds). */
  webcamOffset: number
  capture: CaptureInfo
  /** Kept ranges of the recording (trim + cuts + speed). Never empty. */
  clips: Clip[]
  zooms: ZoomSegment[]
  autoZoom: boolean
  /** Zoom defaults and auto zoom settings (absent in older projects: defaults). */
  zoomSettings?: ZoomSettings
  annotations: Annotation[]
  style: StyleSettings
  cursor: CursorSettings
  webcam: WebcamSettings
  effects: EffectSettings
  audio: AudioSettings
  /** Logo or text stamped on every frame. */
  watermark?: WatermarkSettings
  shapes?: Shape[]
  spotlights?: Spotlight[]
  /** Separate microphone (mic.m4a) and system sound (system.m4a) files kept by the recording. */
  audioStems?: { mic: boolean; system: boolean }
}

export interface ProjectSummary {
  id: string
  name: string
  createdAt: string
  duration: number
  dir: string
}

export interface CaptureSource {
  id: string
  name: string
  thumbnail: string
  kind: 'screen' | 'window'
  displayId?: string
}

/** mp4 (H.264), webm (VP9), mov (H.264 in QuickTime), gif, m4a (audio only). */
export type ExportFormat = 'mp4' | 'gif' | 'webm' | 'mov' | 'm4a'

export interface ExportSettings {
  format: ExportFormat
  /** Output height in pixels (width follows aspect ratio). */
  resolution: 720 | 1080 | 1440 | 2160
  fps: 30 | 60
  quality: 'high' | 'medium' | 'small'
  /** 'auto' uses a GPU encoder when one works, else software. */
  encoder: 'auto' | 'software'
  /** Id of the destination preset these settings came from (e.g. 'youtube-4k'), if any. */
  preset?: string
  /** Aim for this file size (MB) instead of a quality level (two-pass bitrate). */
  targetSizeMB?: number
}

export interface RecordingStatus {
  state: 'idle' | 'countdown' | 'recording' | 'paused' | 'processing'
  elapsed: number
}
