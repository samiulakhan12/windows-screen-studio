/** Normalised (0..1) cursor position relative to the captured display, at time `t` (seconds). */
export interface CursorSample {
  t: number
  x: number
  y: number
}

export interface ClickEvent {
  t: number
  x: number
  y: number
  button: 'left' | 'right' | 'middle'
}

export interface CursorTrack {
  samples: CursorSample[]
  clicks: ClickEvent[]
  /** False when the capture target was a window (cursor coordinates unknown). */
  valid: boolean
}

export type ZoomFocus = { mode: 'cursor' } | { mode: 'fixed'; x: number; y: number }

export interface ZoomSegment {
  id: string
  start: number
  end: number
  scale: number
  focus: ZoomFocus
  /** True when generated by auto zoom (regenerating replaces only these). */
  auto: boolean
}

export type Background =
  | { type: 'gradient'; preset: string }
  | { type: 'color'; color: string }
  | { type: 'image'; path: string }

export type AspectRatio = 'auto' | '16:9' | '9:16' | '1:1' | '4:3'
export type Corner = 'top-left' | 'top-right' | 'bottom-left' | 'bottom-right'

export interface StyleSettings {
  background: Background
  /** Padding as a fraction of the output's shorter side. */
  padding: number
  cornerRadius: number
  shadow: number
  aspectRatio: AspectRatio
}

export interface CursorSettings {
  show: boolean
  size: number
  /** 0 = raw movement, 1 = very smooth. */
  smoothing: number
  clickEffect: boolean
  hideWhenIdle: boolean
}

export interface WebcamSettings {
  show: boolean
  corner: Corner
  /** Diameter as a fraction of output height. */
  size: number
  shape: 'circle' | 'rounded'
}

export interface Project {
  version: 1
  id: string
  name: string
  createdAt: string
  /** Recording duration in seconds. */
  duration: number
  width: number
  height: number
  hasWebcam: boolean
  hasAudio: boolean
  /** Webcam start offset relative to screen start (seconds). */
  webcamOffset: number
  trim: { start: number; end: number }
  zooms: ZoomSegment[]
  autoZoom: boolean
  style: StyleSettings
  cursor: CursorSettings
  webcam: WebcamSettings
}

export interface ProjectSummary {
  id: string
  name: string
  createdAt: string
  duration: number
  dir: string
}

export interface CaptureSource {
  id: string
  name: string
  thumbnail: string
  kind: 'screen' | 'window'
  displayId?: string
}

export interface RecordingOptions {
  sourceId: string
  systemAudio: boolean
}

export type ExportFormat = 'mp4' | 'gif'

export interface ExportSettings {
  format: ExportFormat
  /** Output height in pixels (width follows aspect ratio). */
  resolution: 720 | 1080 | 1440 | 2160
  fps: 30 | 60
  quality: 'high' | 'medium' | 'small'
}

export interface ExportJob {
  width: number
  height: number
  fps: number
  format: ExportFormat
  quality: ExportSettings['quality']
  /** Audio source (proxy file) and trim window; omitted when there is no audio. */
  audio?: { start: number; end: number }
  outputPath: string
}

export interface RecordingStatus {
  state: 'idle' | 'countdown' | 'recording' | 'paused' | 'processing'
  elapsed: number
}
