/** Normalised (0..1) cursor position relative to the captured display, at time `t` (seconds). */
export interface CursorSample {
  t: number
  x: number
  y: number
}

export interface ClickEvent {
  t: number
  x: number
  y: number
  button: 'left' | 'right' | 'middle'
}

/** A shortcut-style keystroke (e.g. "Ctrl + C"); plain typing is never recorded. */
export interface KeyEvent {
  t: number
  label: string
}

export type CursorShape = 'arrow' | 'text' | 'pointer' | 'crosshair' | 'move' | 'resize-ew' | 'resize-ns' | 'wait'

/** Cursor shape changes (only available from the native Windows capture path). */
export interface CursorShapeEvent {
  t: number
  shape: CursorShape
}

export interface CursorTrack {
  samples: CursorSample[]
  clicks: ClickEvent[]
  keys?: KeyEvent[]
  shapes?: CursorShapeEvent[]
  /** Display scale factor (1 = 100%, 1.5 = 150%) of the captured monitor, for cursor sizing. */
  scale?: number
  /** False when the capture target was a window (cursor coordinates unknown). */
  valid: boolean
}

export type ZoomFocus = { mode: 'cursor' } | { mode: 'fixed'; x: number; y: number }

export interface ZoomSegment {
  id: string
  start: number
  end: number
  scale: number
  focus: ZoomFocus
  /** True when generated by auto zoom (regenerating replaces only these). */
  auto: boolean
  /**
   * The click an auto zoom was made for (source seconds, normalised position): with cursor
   * focus the camera aims at it while zooming in and hands back to the cursor shortly after
   * it, so the zoom frames the click even when the cursor arrived just before. Absent in
   * older projects and in zooms made by hand.
   */
  anchor?: { t: number; x: number; y: number }
}

export type Background =
  | { type: 'gradient'; preset: string }
  | { type: 'color'; color: string }
  | { type: 'image'; path: string }

export type AspectRatio = 'auto' | '16:9' | '9:16' | '1:1' | '4:3'
export type Corner = 'top-left' | 'top-right' | 'bottom-left' | 'bottom-right'

export interface StyleSettings {
  background: Background
  /** Padding as a fraction of the output's shorter side. */
  padding: number
  cornerRadius: number
  shadow: number
  aspectRatio: AspectRatio
}

export interface CursorSettings {
  show: boolean
  size: number
  /** 0 = raw movement, 1 = very smooth. */
  smoothing: number
  clickEffect: boolean
  hideWhenIdle: boolean
}

export interface WebcamSettings {
  show: boolean
  corner: Corner
  /** Diameter as a fraction of output height. */
  size: number
  shape: 'circle' | 'rounded'
}

/**
 * A kept piece of the recording, in source seconds. The output video is the
 * clips played back to back, each at its own speed; gaps between clips are cuts.
 */
export interface Clip {
  id: string
  start: number
  end: number
  speed: number
}

export type AnnotationStyle = 'pill' | 'title'

/** Text overlay shown between `start` and `end` (source seconds). */
export interface Annotation {
  id: string
  start: number
  end: number
  text: string
  /** Centre of the text, normalised to the output frame (0..1). */
  x: number
  y: number
  /** Font size as a fraction of the output frame's shorter side. */
  size: number
  style: AnnotationStyle
}

export interface KeystrokeSettings {
  show: boolean
  position: 'bottom' | 'top'
  /** Label size as a fraction of the output frame's shorter side. */
  size: number
}

export interface EffectSettings {
  /** 0 = off, 1 = strong. Applied to camera (zoom/pan) motion. */
  motionBlur: number
  keystrokes: KeystrokeSettings
}

export interface AudioSettings {
  /** Linear gain, 0..2. */
  volume: number
  muted: boolean
}

/** Normalised rectangle (0..1) relative to the captured display. */
export interface NormRect {
  x: number
  y: number
  w: number
  h: number
}

export interface CaptureInfo {
  /** 'native' = Windows Graphics Capture helper; 'chromium' = Electron getDisplayMedia. */
  method: 'native' | 'chromium'
  /** True when the OS cursor is baked into the video pixels. */
  cursorInVideo: boolean
  /** Region of the display that was recorded (already cropped in the proxy), or null for the full source. */
  region: NormRect | null
  /** What was recorded (absent in older projects: 'screen', or 'area' when region is set). */
  target?: 'screen' | 'area' | 'window'
}

export interface Project {
  version: 2
  id: string
  name: string
  createdAt: string
  /** Recording duration in seconds. */
  duration: number
  width: number
  height: number
  hasWebcam: boolean
  hasAudio: boolean
  /** Webcam start offset relative to screen start (seconds). */
  webcamOffset: number
  capture: CaptureInfo
  /** Kept ranges of the recording (trim + cuts + speed). Never empty. */
  clips: Clip[]
  zooms: ZoomSegment[]
  autoZoom: boolean
  annotations: Annotation[]
  style: StyleSettings
  cursor: CursorSettings
  webcam: WebcamSettings
  effects: EffectSettings
  audio: AudioSettings
}

export interface ProjectSummary {
  id: string
  name: string
  createdAt: string
  duration: number
  dir: string
}

export interface CaptureSource {
  id: string
  name: string
  thumbnail: string
  kind: 'screen' | 'window'
  displayId?: string
}

export type ExportFormat = 'mp4' | 'gif'

export interface ExportSettings {
  format: ExportFormat
  /** Output height in pixels (width follows aspect ratio). */
  resolution: 720 | 1080 | 1440 | 2160
  fps: 30 | 60
  quality: 'high' | 'medium' | 'small'
  /** 'auto' uses a GPU encoder when one works, else software. */
  encoder: 'auto' | 'software'
}

export interface RecordingStatus {
  state: 'idle' | 'countdown' | 'recording' | 'paused' | 'processing'
  elapsed: number
}
